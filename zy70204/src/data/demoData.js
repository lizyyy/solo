export function createTestPiece(recipe, observedColor = '#6B8E23', notes = '') {
  return {
    id: uuidv4(),
    recipeId: recipe.id,
    recipeSnapshot: JSON.parse(JSON.stringify(recipe)),
    actualTemperature: recipe.targetTemperature,
    actualAtmosphere: recipe.firingAtmosphere,
    observedColor,
    notes,
    createdAt: new Date().toISOString(),
  };
}
