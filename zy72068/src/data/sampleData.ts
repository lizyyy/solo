import type { ShipRecord } from '@/types';

export const CHANNEL_LENGTH = 100;
export const CHANNEL_WIDTH = 20;
export const BOUNDARY_MARGIN = 2;

const BASE_LNG = 121.4737;
const BASE_LAT = 31.2304;
const LNG_SCALE = 0.001;
const LAT_SCALE = 0.001;

export function geoToScene(lng: number, lat: number): [number, number, number] {
  const x = (lng - BASE_LNG) / LNG_SCALE;
  const z = -(lat - BASE_LAT) / LAT_SCALE;
  return [x, 0, z];
}

export function sceneToGeo(x: number, z: number): { lng: number; lat: number } {
  return {
    lng: BASE_LNG + x * LNG_SCALE,
    lat: BASE_LAT - z * LAT_SCALE,
  };
}

export function isBoundaryRecord(record: ShipRecord): boolean {
  const [x, , z] = geoToScene(record.longitude, record.latitude);
  const hw = CHANNEL_WIDTH / 2;
  const hl = CHANNEL_LENGTH / 2;
  return (
    Math.abs(x) > hw - BOUNDARY_MARGIN ||
    Math.abs(z) > hl - BOUNDARY_MARGIN
  );
}

