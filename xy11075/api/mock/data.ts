const generateRecordNo = (index: number) => {
  const date = new Date();
  date.setDate(date.getDate() - index);
  const dateStr = date.toISOString().slice(0, 10).replace(/-/g, '');
  return `XD${dateStr}${String(index + 1).padStart(3, '0')}`;
};

