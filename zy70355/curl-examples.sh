echo "  -d '{\"pauseType\":\"customer_waiting\",\"reason\":\"测试\"}'"
echo ""

echo "=========================================="
echo "场景 6: 申诉后重算 SLA"
echo "=========================================="
echo ""

echo "# 步骤 1: 假设工单已关闭但标记为超时"
echo "# 先关闭一个工单用于测试"
echo "curl -X POST $BASE_URL/ \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{\"title\":\"超时测试工单\",\"type\":\"technical_support\",\"priority\":\"critical\",\"customerId\":\"C004\"}'"
echo "curl -X POST $BASE_URL/T-000005/start \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{\"assignee\":\"赵六\"}'"
echo "curl -X POST $BASE_URL/T-000005/close"
echo ""

echo "# 步骤 2: 创建申诉"
echo "curl -X POST $BASE_URL/T-000005/appeal \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{"
echo "    \"appealReason\":\"处理期间客户迟迟未回复\",
echo "    \"adjustPauseReason\":\"客户等待时间不应计入 SLA\"
echo "  }'"
echo ""

echo "# 步骤 3: 审批申诉 (确认为客户等待)"
echo "curl -X POST $BASE_URL/T-000005/approve-appeal \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{"
echo "    \"approvedPauseType\":\"customer_waiting\",
echo "    \"approvedReason\":\"经查证，客户确实延迟回复\"
echo "  }'"
echo ""

echo "# 步骤 4: 查看重算后的 SLA 和时间线"
echo "curl -X GET $BASE_URL/T-000005"
echo "curl -X GET $BASE_URL/T-000005/timeline"
echo ""

