#!/bin/bash

BASE_URL="http://localhost:3000/api/tickets"

echo "=========================================="
echo "工单 SLA 暂停 API - Curl 示例命令"
echo "=========================================="
echo ""

echo "【基础信息查询】"
echo "------------------------------------------"
echo ""

echo "# 1. 查询所有优先级及其 SLA"
echo "curl -X GET $BASE_URL/priorities"
echo ""

echo "# 2. 查询所有暂停类型"
echo "curl -X GET $BASE_URL/pause-types"
echo ""

echo "=========================================="
echo "场景 1: 正常关闭的技术支持工单"
echo "=========================================="
echo ""

echo "# 步骤 1: 创建工单 (高优先级 - 8小时 SLA)"
echo "curl -X POST $BASE_URL/ \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{\"title\":\"无法登录系统\",\"type\":\"technical_support\",\"priority\":\"high\",\"customerId\":\"C001\",\"description\":\"用户无法登录后台\"}'"
echo ""

echo "# 步骤 2: 开始处理 (记录 SLA 开始时间)"
echo "curl -X POST $BASE_URL/T-000001/start \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{\"assignee\":\"张三\"}'"
echo ""

echo "# 步骤 3: 关闭工单 (计算 SLA 结果)"
echo "curl -X POST $BASE_URL/T-000001/close"
echo ""

echo "# 步骤 4: 查看详细时间线"
echo "curl -X GET $BASE_URL/T-000001/timeline"
echo ""

echo "=========================================="
echo "场景 2: 客户等待暂停 (不计入 SLA)"
echo "=========================================="
echo ""

echo "# 步骤 1: 创建投诉工单 (紧急优先级 - 2小时 SLA)"
echo "curl -X POST $BASE_URL/ \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{\"title\":\"订单未送达投诉\",\"type\":\"complaint\",\"priority\":\"critical\",\"customerId\":\"C002\"}'"
echo ""

echo "# 步骤 2: 开始处理"
echo "curl -X POST $BASE_URL/T-000002/start \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{\"assignee\":\"李四\"}'"
echo ""

echo "# 步骤 3: 暂停 - 等待客户提供订单号 (客户等待)"
echo "# 注意: 必须提供暂停原因，否则不能生效"
echo "curl -X POST $BASE_URL/T-000002/pause \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{\"pauseType\":\"customer_waiting\",\"reason\":\"需要客户提供订单号查询物流\"}'"
echo ""

echo "# 步骤 4: 恢复计时 (客户已提供信息)"
echo "curl -X POST $BASE_URL/T-000002/resume"
echo ""

echo "# 步骤 5: 关闭工单"
echo "curl -X POST $BASE_URL/T-000002/close"
echo ""

echo "# 步骤 6: 查看时间线 (会显示暂停和恢复事件)"
echo "curl -X GET $BASE_URL/T-000002/timeline"
echo ""

echo "=========================================="
echo "场景 3: 内部等待 (计入 SLA，内部责任)"
echo "=========================================="
echo ""

echo "# 步骤 1: 创建退款工单"
echo "curl -X POST $BASE_URL/ \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{\"title\":\"退款申请\",\"type\":\"refund\",\"priority\":\"medium\",\"customerId\":\"C003\"}'"
echo ""

echo "# 步骤 2: 开始处理"
echo "curl -X POST $BASE_URL/T-000003/start \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{\"assignee\":\"王五\"}'"
echo ""

echo "# 步骤 3: 内部等待 (需要财务审核，这部分计入 SLA)"
echo "curl -X POST $BASE_URL/T-000003/pause \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{\"pauseType\":\"internal_waiting\",\"reason\":\"等待财务部门审核退款\"}'"
echo ""

echo "# 步骤 4: 恢复并关闭"
echo "curl -X POST $BASE_URL/T-000003/resume"
echo "curl -X POST $BASE_URL/T-000003/close"
echo ""

echo "=========================================="
echo "场景 4: 节假日暂停"
echo "=========================================="
echo ""

echo "# 节假日暂停 (系统也会自动排除周末和法定假日)"
echo "curl -X POST $BASE_URL/T-000004/pause \\"
echo "  -H \"Content-Type: application/json\" \\"
echo "  -d '{\"pauseType\":\"holiday\",\"reason\":\"春节假期暂停处理\"}'"
echo ""

echo "=========================================="
echo "场景 5: 测试规则验证"
echo "=========================================="
echo ""

