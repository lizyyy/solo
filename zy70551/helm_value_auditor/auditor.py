SENSITIVE_KEYS = {'password', 'secret', 'token', 'api_key', 'apikey', 'private_key'}


def mask_sensitive_value(key: str, value: Any) -> Any:
    if isinstance(value, dict):
        return {k: mask_sensitive_value(k, v) for k, v in value.items()}
    if isinstance(value, list):
        return [mask_sensitive_value(str(i), v) for i, v in enumerate(value)]
    key_lower = key.lower()
    for s in SENSITIVE_KEYS:
        if s in key_lower:
            return '********'
    return value


@dataclass
class ValueOverrideChain:
    key: str
    sources: List[ValueSource] = field(default_factory=list)
    
    def add_source(self, source: ValueSource):
        self.sources.append(source)
    
    @property
    def current_value(self) -> Any:
        if self.sources:
            return self.sources[-1].value
        return None
    
    @property
    def is_overridden(self) -> bool:
        return len(self.sources) > 1


