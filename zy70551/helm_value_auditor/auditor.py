class HelmValuesAuditor:
    def __init__(self):
        self.loader = YamlLoaderWithLineInfo()
        self.loaded_files: List[LoadedValues] = []
        self.override_chains: Dict[str, ValueOverrideChain] = {}
        self.merged_values: Dict[str, Any] = {}
    
    def load_files(self, file_paths: List[str]):
        for path in file_paths:
            result = self.loader.load_with_source_tracking(path)
            self.loaded_files.append(result)
            
            if result.is_valid:
                for key, source in result.sources.items():
                    if key not in self.override_chains:
                        self.override_chains[key] = ValueOverrideChain(key=key)
                    self.override_chains[key].add_source(source)
                
                self.merged_values = deep_merge(self.merged_values, result.values)
    
    def load_values_files(self, file_paths: List[str]):
        self.load_files(file_paths)
    
    def get_sensitive_keys(self) -> List[str]:
        sensitive = []
        for key in self.override_chains:
            key_lower = key.lower()
            for s in SENSITIVE_KEYS:
                if s in key_lower and key not in sensitive:
                    sensitive.append(key)
        return sensitive
    
    def get_overridden_keys(self) -> List[ValueOverrideChain]:
        return [c for c in self.override_chains.values() if c.is_overridden]
    
    def get_errors(self) -> List:
        errors = []
        for f in self.loaded_files:
            errors.extend(f.errors)
        return errors
    
    def generate_terminal_summary(self) -> str:
        lines = []
        lines.append('=' * 80)
        lines.append('HELM VALUES AUDIT SUMMARY')
        lines.append('=' * 80)
        lines.append('')
        
        lines.append(f'Files loaded: {len(self.loaded_files)}')
        for f in self.loaded_files:
            status = '[OK]' if f.is_valid else '[ERROR]'
            lines.append(f'  {status} {f.file_path}')
        lines.append('')
        
        overridden = self.get_overridden_keys()
        lines.append(f'Overridden keys: {len(overridden)}')
        for chain in overridden:
            lines.append(f'  {chain.key}:')
            for i, src in enumerate(chain.sources):
                prefix = '->' if i == len(chain.sources) - 1 else '  '
                val = mask_sensitive_value(chain.key, src.value)
                lines.append(f'       {prefix} {val} @ {os.path.basename(src.file_path)}')
        lines.append('')
        
        sensitive = self.get_sensitive_keys()
        lines.append(f'Sensitive keys found: {len(sensitive)}')
        for k in sensitive:
            lines.append(f'  {k}')
        lines.append('')
        
        errors = self.get_errors()
        if errors:
            lines.append(f'Parse errors: {len(errors)}')
            for e in errors:
                lines.append(f'  {e.file_path}:{e.line_number or "?"}:{e.column or "?"}')
                lines.append(f'    {e.message}')
                if e.raw_content:
                    lines.append(f'    {e.raw_content}')
            lines.append('')
        
        lines.append('=' * 80)
        return '\n'.join(lines)
    
    def print_terminal_summary(self):
        print(self.generate_terminal_summary())
    
    def generate_json_report(self) -> str:
        report = {
            'files_loaded': [f.file_path for f in self.loaded_files],
            'merged_values': mask_sensitive_value('root', self.merged_values),
            'override_chains': [
                {
                    'key': c.key,
                    'is_sensitive': any(s in c.key.lower() for s in SENSITIVE_KEYS),
                    'sources': [
                        {
                            'file_path': s.file_path,
                            'line_number': s.line_number,
                            'value': mask_sensitive_value(c.key, s.value)
                        } for s in c.sources
                    ]
                } for c in self.override_chains.values()
            ],
            'errors': [
                {
                    'file_path': e.file_path,
                    'line_number': e.line_number,
                    'column': e.column,
                    'message': e.message,
                    'raw_content': e.raw_content
                } for e in self.get_errors()
            ]
        }
        return json.dumps(report, indent=2, ensure_ascii=False)
    
    def generate_html_report(self) -> str:
        template = Template(HTML_TEMPLATE)
        chains_data = []
        for c in self.override_chains.values():
            is_sensitive = any(s in c.key.lower() for s in SENSITIVE_KEYS)
            chains_data.append({
                'key': c.key,
                'is_sensitive': is_sensitive,
                'sources': [
                    {
                        'file_path': os.path.basename(s.file_path),
                        'line_number': s.line_number,
                        'value': mask_sensitive_value(c.key, s.value)
                    } for s in c.sources
                ]
            })
        
        files_data = [
            {'path': f.file_path, 'is_valid': f.is_valid}
            for f in self.loaded_files
        ]
        
        errors_data = self.get_errors()
        
        return template.render(
            files=files_data,
            chains=chains_data,
            errors=errors_data
        )
