const db = require('../database/db');

async function 检查未消毒器械(器械编号) {
  const 最新记录 = await db.prepare(`
    SELECT 
      j.记录编号,
      j.器械编号,
      q.器械名称,
      q.器械类别,
      j.归还日期时间,
      j.消毒状态,
      j.状态 as 借还状态
    FROM 借还明细 j
    JOIN 器械档案 q ON j.器械编号 = q.器械编号
    WHERE j.器械编号 = ?
    ORDER BY j.归还日期时间 DESC
    LIMIT 1
  `).get(器械编号);

  if (最新记录 && 最新记录.消毒状态 === '未消毒' && 最新记录.借还状态 === '已归还') {
    return {
      有问题: true,
      问题类型: '未消毒器械',
      问题描述: `器械【${最新记录.器械名称}】上次归还后未消毒`,
      关键信息: {
        器械编号: 最新记录.器械编号,
        器械名称: 最新记录.器械名称,
        归还时间: 最新记录.归还日期时间,
        当前消毒状态: 最新记录.消毒状态
      },
      下一步操作: '请先完成消毒登记后再借出',
      需要补充材料: ['消毒记录']
    };
  }

  return { 有问题: false };
}

async function 检查借还一致性() {
  const 问题列表 = [];

  const 借用中无对应记录 = await db.prepare(`
    SELECT 
      q.器械编号,
      q.器械名称,
      q.器械类别,
      q.当前状态,
      q.当前位置
    FROM 器械档案 q
    WHERE q.当前状态 = '借用中'
    AND NOT EXISTS (
      SELECT 1 FROM 借还明细 j 
      WHERE j.器械编号 = q.器械编号 AND j.状态 = '借用中'
    )
  `).all();

  借用中无对应记录.forEach(item => {
    问题列表.push({
      问题类型: '状态不一致',
      问题描述: `器械【${item.器械名称}】档案显示借用中，但无借用记录`,
      关键信息: item,
      下一步操作: '请补录该器械的借用记录或修正档案状态',
      需要补充材料: ['借用记录']
    });
  });

  const 有借用记录但状态不匹配 = await db.prepare(`
    SELECT 
      j.记录编号,
      j.器械编号,
      q.器械名称,
      q.器械类别,
      j.借用人姓名,
      j.借用日期时间,
      j.状态 as 借还状态,
      q.当前状态 as 档案状态
    FROM 借还明细 j
    JOIN 器械档案 q ON j.器械编号 = q.器械编号
    WHERE j.状态 = '借用中' AND q.当前状态 != '借用中'
  `).all();

  有借用记录但状态不匹配.forEach(item => {
    问题列表.push({
      问题类型: '状态不一致',
      问题描述: `器械【${item.器械名称}】有借用记录但档案状态不匹配`,
      关键信息: item,
      下一步操作: '请核对并更新器械档案状态为借用中',
      需要补充材料: ['状态修正记录']
    });
  });

  const 归还无消毒记录 = await db.prepare(`
    SELECT 
      j.记录编号,
      j.器械编号,
      q.器械名称,
      q.器械类别,
      j.归还人姓名,
      j.归还日期时间,
      j.消毒状态
    FROM 借还明细 j
    JOIN 器械档案 q ON j.器械编号 = q.器械编号
    WHERE j.状态 = '已归还' 
    AND j.消毒状态 = '未消毒'
    AND DATE(j.归还日期时间) < DATE('now', '-1 day')
  `).all();

  归还无消毒记录.forEach(item => {
    问题列表.push({
      问题类型: '消毒逾期',
      问题描述: `器械【${item.器械名称}】归还超过1天仍未消毒`,
      关键信息: item,
      下一步操作: '请立即安排消毒并补录消毒记录',
      需要补充材料: ['消毒记录']
    });
  });

  return {
    检查时间: new Date().toISOString(),
    问题总数: 问题列表.length,
    问题列表: 问题列表
  };
}

async function 检查借用前置条件(器械编号) {
  const 前置问题 = [];

  const 消毒检查 = await 检查未消毒器械(器械编号);
  if (消毒检查.有问题) {
    前置问题.push(消毒检查);
  }

  const 器械状态 = await db.prepare(`
    SELECT 当前状态, 器械名称 FROM 器械档案 WHERE 器械编号 = ?
  `).get(器械编号);

  if (!器械状态) {
    前置问题.push({
      有问题: true,
      问题类型: '器械不存在',
      问题描述: '器械编号不存在',
      下一步操作: '请核对器械编号或先建立器械档案',
      需要补充材料: ['器械档案']
    });
  } else if (器械状态.当前状态 === '借用中') {
    前置问题.push({
      有问题: true,
      问题类型: '器械已借出',
      问题描述: `器械【${器械状态.器械名称}】当前已被借用`,
      下一步操作: '请等待归还后再借或选择其他器械',
      需要补充材料: []
    });
  } else if (器械状态.当前状态 === '消毒中') {
    前置问题.push({
      有问题: true,
      问题类型: '消毒中',
      问题描述: `器械【${器械状态.器械名称}】正在消毒中`,
      下一步操作: '请等待消毒完成后再借出',
      需要补充材料: []
    });
  }

  return {
    可借用: 前置问题.length === 0,
    问题列表: 前置问题
  };
}

module.exports = {
  检查未消毒器械,
  检查借还一致性,
  检查借用前置条件
};
