const createValidationResult = (
  status: 'passed' | 'failed' | 'retry',
  checks: ValidationCheck[],
  manualReview = false,
  manualReason?: string
): ValidationResult => ({
  overallStatus: status,
  checks,
  needsManualReview: manualReview,
  manualReviewReason: manualReason,
  canRetry: status !== 'passed',
  retryInstructions: status === 'retry' ? '请修正数据后重新验证' : undefined,
});

