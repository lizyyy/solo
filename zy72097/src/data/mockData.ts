const createProcessHistory = (dataId: string, records: Omit<ProcessRecord, 'id' | 'dataId' | 'operatedAt'>[]): ProcessRecord[] => {
  return records.map((r, idx) => ({
    id: `${dataId}-PROC-${idx + 1}`,
    dataId,
    operatedAt: now,
    ...r,
  }));
};

const createJudgment = (dataId: string, judgment: Omit<JudgmentRecord, 'id' | 'dataId' | 'judgedAt'>): JudgmentRecord => ({
  id: `${dataId}-JUD-1`,
  dataId,
  judgedAt: now,
  ...judgment,
});

