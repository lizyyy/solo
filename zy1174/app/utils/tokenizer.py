class Tokenizer:
    def __init__(self, tokenizer_type: str = 'jieba'):
        self.tokenizer_type = tokenizer_type.lower()
        
    def tokenize(self, text: str) -> List[str]:
        if not text or not isinstance(text, str):
            return []
        
        text = text.strip()
        if not text:
            return []
        
        if self.tokenizer_type == 'jieba':
            return list(jieba.cut(text))
        elif self.tokenizer_type == 'space':
            return text.split()
        elif self.tokenizer_type == 'char':
            return list(text)
        else:
            return list(jieba.cut(text))
    
    def tokenize_batch(self, texts: List[str]) -> List[List[str]]:
        return [self.tokenize(text) for text in texts]

class StopWordFilter:
    def __init__(self, language: str = 'chinese', custom_stopwords: Optional[List[str]] = None):
        self.language = language.lower()
        self.stopwords = self._load_stopwords()
        
        if custom_stopwords:
            self.stopwords.update(set(custom_stopwords))
    
    def _load_stopwords(self) -> set:
        if self.language == 'chinese':
            return CHINESE_STOPWORDS.copy()
        elif self.language == 'english':
            return ENGLISH_STOPWORDS.copy()
        elif self.language == 'both':
            return CHINESE_STOPWORDS.copy().union(ENGLISH_STOPWORDS.copy())
        else:
            return set()
    
    def filter(self, tokens: List[str]) -> List[str]:
        if not tokens:
            return []
        
        return [token for token in tokens if token.strip() and token.lower() not in self.stopwords]
    
    def filter_batch(self, token_lists: List[List[str]]) -> List[List[str]]:
        return [self.filter(tokens) for tokens in token_lists]
    
    def add_stopword(self, word: str):
        self.stopwords.add(word.lower())
    
    def remove_stopword(self, word: str):
        self.stopwords.discard(word.lower())

class TextProcessor:
    def __init__(self, tokenizer_type: str = 'jieba', stopword_lang: str = 'chinese', 
                 custom_stopwords: Optional[List[str]] = None):
        self.tokenizer = Tokenizer(tokenizer_type)
        self.stopword_filter = StopWordFilter(stopword_lang, custom_stopwords)
    
    def process(self, text: str) -> List[str]:
        tokens = self.tokenizer.tokenize(text)
        filtered_tokens = self.stopword_filter.filter(tokens)
        return filtered_tokens
    
    def process_batch(self, texts: List[str]) -> List[List[str]]:
        return [self.process(text) for text in texts]
    
    def clean_text(self, text: str) -> str:
        if not text or not isinstance(text, str):
            return ''
        
        text = re.sub(r'\s+', ' ', text)
        text = re.sub(r'[^\u4e00-\u9fa5a-zA-Z0-9\s]', '', text)
        return text.strip()
    
    def clean_and_process(self, text: str) -> List[str]:
        clean_text = self.clean_text(text)
        return self.process(clean_text)
