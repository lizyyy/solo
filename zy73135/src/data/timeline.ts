export const getTimelineByRecordId = (recordId: string, events: TimelineEvent[]): TimelineEvent[] => {
  return events
    .filter(e => e.recordId === recordId)
    .sort((a, b) => new Date(a.eventTime).getTime() - new Date(b.eventTime).getTime());
};
