import type { RobotTrajectory } from '../utils/types'

const T = 1717000000000

function makeTrajectory(
  id: string,
  robotId: string,
  status: RobotTrajectory['status'],
  sourceLine: number,
  points: { x: number; z: number; t: number; battery: number; taskId?: string }[],
  sourceRaw?: string,
): RobotTrajectory {
  return {
    id,
    robotId,
    status,
    source: { file: 'trajectories_20250530.csv', line: sourceLine, rawValue: sourceRaw },
    points: points.map((p) => ({
      x: p.x,
      y: 0.5,
      z: p.z,
      timestamp: T + p.t * 1000,
      batteryLevel: p.battery,
      taskId: p.taskId,
    })),
  }
}

