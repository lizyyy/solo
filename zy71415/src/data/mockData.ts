export function generateAlerts(accounts: SubAccount[]): Alert[] {
  const alerts: Alert[] = []
  accounts.forEach((acc) => {
    if (acc.isReserveShortage) {
      alerts.push({
        id: `alert-rs-${acc.id}`,
        type: "reserve_shortage",
        accountId: acc.id,
        accountName: acc.accountName,
        bank: acc.bank,
        message: `留底不足：${acc.accountName}余额${(acc.balance / 10000).toFixed(1)}万元，需留底${(acc.reserveRequired / 10000).toFixed(1)}万元`,
        timestamp: acc.collectDate + "T09:30:00",
        severity: "warning",
      })
    }
    if (acc.isLimitExceeded) {
      alerts.push({
        id: `alert-le-${acc.id}`,
        type: "limit_exceeded",
        accountId: acc.id,
        accountName: acc.accountName,
        bank: acc.bank,
        message: `限额超用：${acc.accountName}超限${(Math.abs(acc.limitRemain) / 10000).toFixed(1)}万元`,
        timestamp: acc.collectDate + "T09:15:00",
        severity: "critical",
      })
    }
    if (acc.isDuplicateCollect) {
      alerts.push({
        id: `alert-dc-${acc.id}`,
        type: "duplicate_collect",
        accountId: acc.id,
        accountName: acc.accountName,
        bank: acc.bank,
        message: `重复归集：${acc.accountName}回执晚到导致重复归集，需核实`,
        timestamp: acc.collectDate + "T16:00:00",
        severity: "critical",
      })
    }
  })
  return alerts.sort((a, b) => (a.severity === "critical" ? -1 : 1))
}

