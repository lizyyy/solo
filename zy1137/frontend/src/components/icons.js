export const BatteryIcon = (level) => {
  let color = '#10b981'
  if (level < 10) color = '#dc2626'
  else if (level < 20) color = '#f59e0b'
  else if (level < 50) color = '#3b82f6'
  
  return `
    <svg fill="none" stroke="currentColor" viewBox="0 0 24 24" width="18" height="18">
      <rect x="1" y="7" width="18" height="10" rx="2" ry="2" stroke="${color}" fill="none" stroke-width="2"></rect>
      <path d="M23 11v2" stroke="${color}" stroke-width="2" stroke-linecap="round"></path>
      <rect x="3" y="9" width="${Math.max(0, (level || 0) * 14 / 100)}" height="6" rx="1" fill="${color}"></rect>
    </svg>
  `
}

export const SignalIcon = (rssi) => {
  let bars = 0
  let color = '#10b981'
  
  if (rssi >= -60) { bars = 4; color = '#10b981' }
  else if (rssi >= -70) { bars = 3; color = '#3b82f6' }
  else if (rssi >= -80) { bars = 2; color = '#f59e0b' }
  else if (rssi >= -90) { bars = 1; color = '#ea580c' }
  else { bars = 0; color = '#dc2626' }
  
  const rects = [0, 1, 2, 3].map(i => {
    const height = 4 + i * 3
    const y = 20 - height
    const fill = i < bars ? color : '#e5e7eb'
    return `<rect x="${6 + i * 4}" y="${y}" width="3" height="${height}" rx="1" fill="${fill}"></rect>`
  }).join('')
  
  return `
    <svg fill="none" stroke="none" viewBox="0 0 24 24" width="18" height="18">
      ${rects}
    </svg>
  `
}

