class SampleDataGenerator:
    def __init__(self):
        pass

    def generate_transcript_md(self) -> str:
        return SAMPLE_TRANSCRIPT_MD

    def generate_evidence_csv(self) -> str:
        return SAMPLE_EVIDENCE_CSV

    def generate_cross_exam_json(self) -> str:
        return SAMPLE_CROSS_EXAM_JSON

    def generate_judgment_draft_md(self) -> str:
        return SAMPLE_JUDGMENT_DRAFT_MD

    def generate_all_samples(
        self,
        output_dir: Path,
        prefix: str = "",
    ) -> Dict[str, Path]:
        output_dir.mkdir(parents=True, exist_ok=True)

        files = {}

        transcript_path = output_dir / f"{prefix}庭审笔录.md"
        transcript_path.write_text(self.generate_transcript_md(), encoding="utf-8")
        files["transcript"] = transcript_path

        evidence_path = output_dir / f"{prefix}证据目录.csv"
        evidence_path.write_text(self.generate_evidence_csv(), encoding="utf-8")
        files["evidence_list"] = evidence_path

        cross_exam_path = output_dir / f"{prefix}举证质证记录.json"
        cross_exam_path.write_text(self.generate_cross_exam_json(), encoding="utf-8")
        files["cross_examination"] = cross_exam_path

        judgment_path = output_dir / f"{prefix}裁判要点草稿.md"
        judgment_path.write_text(self.generate_judgment_draft_md(), encoding="utf-8")
        files["judgment_draft"] = judgment_path

        return files


def generate_sample_files(output_dir: Path, prefix: str = "") -> Dict[str, Path]:
    generator = SampleDataGenerator()
    return generator.generate_all_samples(output_dir, prefix)
