import express, {
  type Request,
  type Response,
  type NextFunction,
} from 'express'
import cors from 'cors'
import path from 'path'
import dotenv from 'dotenv'
import { fileURLToPath } from 'url'
import projectRoutes from './routes/projects.js'
import lightRecordRoutes from './routes/light-records.js'
import trackParamsRoutes from './routes/track-params.js'
import carParamsRoutes from './routes/car-params.js'
import estimationRoutes from './routes/estimations.js'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

dotenv.config()

const app: express.Application = express()

app.use(cors())
app.use(express.json({ limit: '10mb' }))
app.use(express.urlencoded({ extended: true, limit: '10mb' }))

app.use('/api/projects', projectRoutes)
app.use('/api/light-records', lightRecordRoutes)
app.use('/api/track-params', trackParamsRoutes)
app.use('/api/car-params', carParamsRoutes)
app.use('/api/estimations', estimationRoutes)

app.use(
  '/api/health',
  (req: Request, res: Response, next: NextFunction): void => {
    res.status(200).json({
      success: true,
      message: 'ok',
    })
  },
)

app.use((error: Error, req: Request, res: Response, next: NextFunction) => {
  console.error('Server error:', error)
  res.status(500).json({
    success: false,
    error: 'Server internal error',
  })
})

app.use((req: Request, res: Response) => {
  res.status(404).json({
    success: false,
    error: 'API not found',
  })
})

export default app
