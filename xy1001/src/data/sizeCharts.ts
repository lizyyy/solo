export const allSizeCharts: SizeChart[] = [...dogSizeCharts, ...catSizeCharts];

export function getSizeChartsByPetType(petType: 'dog' | 'cat'): SizeChart[] {
  return petType === 'dog' ? dogSizeCharts : catSizeCharts;
}

export function getSizeChartsByCriteria(petType: 'dog' | 'cat', bodyShape?: string): SizeChart[] {
  let charts = getSizeChartsByPetType(petType);
  if (bodyShape) {
    charts = charts.filter(chart => chart.bodyShape === bodyShape);
  }
  return charts;
}

export function findBestSize(
  petType: 'dog' | 'cat',
  bodyShape: string,
  chest: number,
  length: number,
  neck?: number,
  weight?: number
): { bestSize: SizeChart | null; confidence: 'exact' | 'between' | 'borderline'; alternatives: SizeChart[] } {
  
  const charts = getSizeChartsByCriteria(petType, bodyShape);
  
  if (charts.length === 0) {
    return { bestSize: null, confidence: 'exact', alternatives: [] };
  }
  
  const sizeScores: { chart: SizeChart; score: number; isExact: boolean; isBorderline: boolean }[] = [];
  
  for (const chart of charts) {
    let score = 0;
    let exactMatches = 0;
    let borderlineMatches = 0;
    
    const chestInRange = chest >= chart.chestMin && chest <= chart.chestMax;
    const lengthInRange = length >= chart.lengthMin && length <= chart.lengthMax;
    
    if (chestInRange) {
      const chestMid = (chart.chestMin + chart.chestMax) / 2;
      const chestDeviation = Math.abs(chest - chestMid) / (chart.chestMax - chart.chestMin);
      score += (1 - chestDeviation) * 0.4;
      exactMatches++;
    } else {
      const chestDiff = chest < chart.chestMin 
        ? chart.chestMin - chest 
        : chest - chart.chestMax;
      if (chestDiff <= 2) {
        score += 0.2;
        borderlineMatches++;
      }
    }
    
    if (lengthInRange) {
      const lengthMid = (chart.lengthMin + chart.lengthMax) / 2;
      const lengthDeviation = Math.abs(length - lengthMid) / (chart.lengthMax - chart.lengthMin);
      score += (1 - lengthDeviation) * 0.4;
      exactMatches++;
    } else {
      const lengthDiff = length < chart.lengthMin 
        ? chart.lengthMin - length 
        : length - chart.lengthMax;
      if (lengthDiff <= 2) {
        score += 0.2;
        borderlineMatches++;
      }
    }
    
    if (neck !== undefined && neck >= chart.neckMin && neck <= chart.neckMax) {
      const neckMid = (chart.neckMin + chart.neckMax) / 2;
      const neckDeviation = Math.abs(neck - neckMid) / (chart.neckMax - chart.neckMin);
      score += (1 - neckDeviation) * 0.15;
      exactMatches++;
    }
    
    if (weight !== undefined && chart.weightMin !== undefined && chart.weightMax !== undefined) {
      if (weight >= chart.weightMin && weight <= chart.weightMax) {
        const weightMid = (chart.weightMin + chart.weightMax) / 2;
        const weightDeviation = Math.abs(weight - weightMid) / (chart.weightMax - chart.weightMin);
        score += (1 - weightDeviation) * 0.05;
        exactMatches++;
      }
    }
    
    if (exactMatches >= 2) {
      sizeScores.push({ chart, score, isExact: true, isBorderline: false });
    } else if (borderlineMatches >= 1) {
      sizeScores.push({ chart, score, isExact: false, isBorderline: true });
    }
  }
  
  if (sizeScores.length === 0) {
    return { bestSize: null, confidence: 'exact', alternatives: [] };
  }
  
  sizeScores.sort((a, b) => b.score - a.score);
  
  const exactMatches = sizeScores.filter(s => s.isExact);
  const borderlineMatches = sizeScores.filter(s => s.isBorderline);
  
  let bestSize: SizeChart | null = null;
  let confidence: 'exact' | 'between' | 'borderline' = 'exact';
  
  if (exactMatches.length >= 1) {
    bestSize = exactMatches[0].chart;
    if (exactMatches.length >= 2 && Math.abs(exactMatches[0].score - exactMatches[1].score) < 0.1) {
      confidence = 'between';
    } else {
      confidence = 'exact';
    }
  } else if (borderlineMatches.length >= 1) {
    bestSize = borderlineMatches[0].chart;
    confidence = 'borderline';
  }
  
  const alternatives = sizeScores
    .slice(1, 4)
    .map(s => s.chart)
    .filter(c => c.id !== bestSize?.id);
  
  return { bestSize, confidence, alternatives };
}

export function generateSizeReasoning(
  chest: number,
  length: number,
  bestSize: SizeChart,
  confidence: string,
  alternatives: SizeChart[]
): string {
  let reasoning = `根据测量数据，胸围 ${chest}cm，背长 ${length}cm。\n`;
  reasoning += `推荐尺码：${bestSize.sizeCode}，适合胸围 ${bestSize.chestMin}-${bestSize.chestMax}cm，背长 ${bestSize.lengthMin}-${bestSize.lengthMax}cm。\n`;
  
  if (confidence === 'exact') {
    reasoning += '测量数据完全在推荐尺码范围内，穿着效果应该非常贴合。';
  } else if (confidence === 'between') {
    reasoning += '测量数据处于两个尺码的边界，建议根据宠物的实际体型和衣物款式选择。';
    if (alternatives.length > 0) {
      reasoning += ` 备选尺码：${alternatives[0].sizeCode}。`;
    }
  } else if (confidence === 'borderline') {
    reasoning += '测量数据接近推荐尺码范围，如果宠物体型较圆建议选大一码，体型较瘦建议选小一码。';
  }
  
  reasoning += '\n\n温馨提示：优先以胸围为参考标准（衣物过紧会影响呼吸和活动），背长以盖过背部主要部分为准。';
  
  return reasoning;
}
