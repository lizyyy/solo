export const getStatsData = (applications: BoothApplication[]): StatsData => {
  return {
    totalApplications: applications.length,
    pendingApproval: applications.filter(a => a.status === 'pending_approval' || a.status === 'material_review').length,
    pendingTeardown: applications.filter(a => a.status === 'teardown_pending').length,
    pendingDeduction: applications.filter(a => a.teardown.status === 'failed' && a.deposit.status === 'refund_pending').length,
    inProgress: applications.filter(a => ['deposit_paid', 'setup_confirmed', 'in_use'].includes(a.status)).length,
    completed: applications.filter(a => a.status === 'completed').length,
    issues: applications.filter(a => a.hasScheduleConflict || a.hasMaterialIssue || a.hasElectricityIssue || a.hasDepositIssue || a.hasTeardownIssue).length,
  };
};
