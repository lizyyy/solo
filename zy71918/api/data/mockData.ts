let clipsStore: Clip[] = JSON.parse(JSON.stringify(mockClips));
const usersStore: User[] = JSON.parse(JSON.stringify(mockUsers));

export function getClipsStore(): Clip[] {
  return clipsStore;
}

export function setClipsStore(clips: Clip[]): void {
  clipsStore = clips;
}

export function updateClipInStore(clip: Clip): void {
  const index = clipsStore.findIndex(c => c.id === clip.id);
  if (index !== -1) {
    clipsStore[index] = clip;
  }
}

export function addClipToStore(clip: Clip): void {
  clipsStore.unshift(clip);
}

export function getUsersStore(): User[] {
  return usersStore;
}
