def 生成分发记录编号():
    前缀 = 'FH' + datetime.now().strftime('%Y%m%d')
    最后记录 = 画材包分发记录.query.order_by(画材包分发记录.分发记录编号.desc()).first()
    if 最后记录 and 最后记录.分发记录编号.startswith(前缀):
        序号 = int(最后记录.分发记录编号[-4:]) + 1
    else:
        序号 = 1
    return f'{前缀}{序号:04d}'


def 记录异常(异常类型, 异常描述, 涉及学号=None, 涉及分发记录编号=None, 涉及包类型编号=None, 原班级编号=None, 新班级编号=None):
    异常日志 = 分发异常日志(
        异常类型=异常类型,
        异常描述=异常描述,
        涉及学号=涉及学号,
        涉及分发记录编号=涉及分发记录编号,
        涉及包类型编号=涉及包类型编号,
        原班级编号=原班级编号,
        新班级编号=新班级编号
    )
    db.session.add(异常日志)
    db.session.commit()
    return 异常日志.异常编号


@app.route('/api/distribute', methods=['POST'])
def 分发画材包():
    数据 = request.get_json()
    
    学号 = 数据.get('学号')
    包类型编号 = 数据.get('包类型编号')
    分发人 = 数据.get('分发人', '系统自动')
    是否补领 = 数据.get('是否补领', False)
    原分发记录编号 = 数据.get('原分发记录编号')
    
    if not 学号 or not 包类型编号:
        return jsonify({
            '错误码': 'PARAM_MISSING',
            '错误信息': '学号和包类型编号为必填参数',
            '建议操作': '请检查输入参数，确保学号和包类型编号都已填写'
        }), 400
    
    学生信息 = 学生.query.get(学号)
    if not 学生信息:
        return jsonify({
            '错误码': 'STUDENT_NOT_FOUND',
            '错误信息': f'未找到学号为 {学号} 的学生信息',
            '建议操作': '请先在系统中注册该学生信息后再进行分发'
        }), 404
    
    包类型信息 = 画材包类型.query.get(包类型编号)
    if not 包类型信息:
        return jsonify({
            '错误码': 'PACKAGE_NOT_FOUND',
            '错误信息': f'未找到编号为 {包类型编号} 的画材包类型',
            '建议操作': '请先配置该画材包类型信息'
        }), 404
    
    库存信息 = 画材库存.query.filter_by(包类型编号=包类型编号).first()
    if not 库存信息 or 库存信息.当前库存量 <= 0:
        return jsonify({
            '错误码': 'INVENTORY_SHORTAGE',
            '错误信息': f'画材包 {包类型信息.包类型名称} 当前库存不足',
            '当前库存量': 库存信息.当前库存量 if 库存信息 else 0,
            '建议操作': '请先进行画材包采购入库后再进行分发'
        }), 409
    
    已有分发记录 = 画材包分发记录.query.filter_by(
        学号=学号,
        包类型编号=包类型编号,
        领取状态='已领取'
    ).first()
    
    if 已有分发记录 and not 是否补领:
        异常编号 = 记录异常(
            异常类型='重复分发冲突',
            异常描述=f'学生 {学生信息.姓名} (学号: {学号}) 已领取过 {包类型信息.包类型名称}，且未标记为补领',
            涉及学号=学号,
            涉及分发记录编号=已有分发记录.分发记录编号,
            涉及包类型编号=包类型编号
        )
        return jsonify({
            '错误码': 'DUPLICATE_DISTRIBUTION',
            '错误信息': f'该学生已领取过此类型画材包，禁止静默覆盖原记录',
            '异常编号': 异常编号,
            '原有分发记录': {
                '分发记录编号': 已有分发记录.分发记录编号,
                '分发时间': 已有分发记录.分发时间.strftime('%Y-%m-%d %H:%M:%S'),
                '领取状态': 已有分发记录.领取状态
            },
            '建议操作': '如确需补领，请在请求中设置 is_reissue=true 并提供原分发记录编号'
        }), 409
    
    if 是否补领:
        if 原分发记录编号:
            原记录 = 画材包分发记录.query.get(原分发记录编号)
            if not 原记录:
                return jsonify({
                    '错误码': 'ORIGINAL_RECORD_NOT_FOUND',
                    '错误信息': f'未找到原分发记录 {原分发记录编号}',
                    '建议操作': '请核实原分发记录编号是否正确'
                }), 404
            
            if 原记录.学号 != 学号:
                异常编号 = 记录异常(
                    异常类型='跨班补领冲突',
                    异常描述=f'尝试使用其他学生的分发记录进行补领。原记录学号: {原记录.学号}, 当前申请学号: {学号}',
                    涉及学号=学号,
                    涉及分发记录编号=原分发记录编号,
                    涉及包类型编号=包类型编号
                )
                return jsonify({
                    '错误码': 'CROSS_STUDENT_REISSUE',
                    '错误信息': '补领记录与原领取学生不一致，存在跨班补领风险',
                    '异常编号': 异常编号,
                    '原记录学生': 原记录.学号,
                    '当前申请学生': 学号,
                    '建议操作': '请确认补领学生是否正确，或按跨班补领流程进行特殊审批'
                }), 409
            
            if 原记录.包类型编号 != 包类型编号:
                异常编号 = 记录异常(
                    异常类型='补领包类型不一致',
                    异常描述=f'补领包类型与原记录不一致。原记录包类型: {原记录.包类型编号}, 当前申请包类型: {包类型编号}',
                    涉及学号=学号,
                    涉及分发记录编号=原分发记录编号,
                    涉及包类型编号=包类型编号
                )
                return jsonify({
                    '错误码': 'PACKAGE_TYPE_MISMATCH',
                    '错误信息': '补领包类型与原记录包类型不一致',
                    '异常编号': 异常编号,
                    '原记录包类型': 原记录.包类型编号,
                    '当前申请包类型': 包类型编号,
                    '建议操作': '请确认是否需要更换包类型，如需更换请走特殊审批流程'
                }), 409
    
    分发记录编号 = 生成分发记录编号()
    
    try:
        库存信息.当前库存量 -= 1
        
        新记录 = 画材包分发记录(
            分发记录编号=分发记录编号,
            学号=学号,
            包类型编号=包类型编号,
            分发人=分发人,
            领取状态='已领取',
            领取确认时间=datetime.now(),
            补领标记=是否补领,
            原分发记录编号=原分发记录编号
        )
        db.session.add(新记录)
        db.session.commit()
        
        return jsonify({
            '状态': '成功',
            '消息': '画材包分发成功',
            '分发记录编号': 分发记录编号,
            '学生信息': {
                '学号': 学生信息.学号,
                '姓名': 学生信息.姓名,
                '班级': 学生信息.所属班级.班级名称
            },
            '画材包信息': {
                '包类型编号': 包类型信息.包类型编号,
                '包类型名称': 包类型信息.包类型名称
            },
            '剩余库存': 库存信息.当前库存量
        }), 201
        
    except Exception as e:
        db.session.rollback()
        异常编号 = 记录异常(
            异常类型='库存扣重异常',
            异常描述=f'分发过程中发生错误: {str(e)}',
            涉及学号=学号,
            涉及包类型编号=包类型编号
        )
        return jsonify({
            '错误码': 'DISTRIBUTION_ERROR',
            '错误信息': '画材包分发过程中发生异常，已自动回滚',
            '异常编号': 异常编号,
            '错误详情': str(e),
            '建议操作': '请联系技术支持人员处理'
        }), 500


@app.route('/api/distributions', methods=['GET'])
def 查询分发记录():
    学号 = request.args.get('学号')
    班级编号 = request.args.get('班级编号')
    包类型编号 = request.args.get('包类型编号')
    领取状态 = request.args.get('领取状态')
    
    查询 = 画材包分发记录.query
    
    if 学号:
        查询 = 查询.filter_by(学号=学号)
    if 班级编号:
        查询 = 查询.join(学生).filter(学生.班级编号 == 班级编号)
    if 包类型编号:
        查询 = 查询.filter_by(包类型编号=包类型编号)
    if 领取状态:
        查询 = 查询.filter_by(领取状态=领取状态)
    
    记录列表 = 查询.order_by(画材包分发记录.分发时间.desc()).all()
    
    结果 = []
    for 记录 in 记录列表:
        结果.append({
            '分发记录编号': 记录.分发记录编号,
            '学号': 记录.学号,
            '学生姓名': 记录.领取学生.姓名,
            '班级': 记录.领取学生.所属班级.班级名称,
            '包类型编号': 记录.包类型编号,
            '包类型名称': 记录.包类型.包类型名称,
            '分发时间': 记录.分发时间.strftime('%Y-%m-%d %H:%M:%S'),
            '分发人': 记录.分发人,
            '领取状态': 记录.领取状态,
            '补领标记': 记录.补领标记,
            '原分发记录编号': 记录.原分发记录编号,
            '备注': 记录.备注
        })
    
    return jsonify({
        '状态': '成功',
        '记录总数': len(结果),
        '分发记录': 结果
    }), 200


@app.route('/api/export', methods=['GET'])
def 导出分发记录():
    格式 = request.args.get('格式', 'json')
    开始日期 = request.args.get('开始日期')
    结束日期 = request.args.get('结束日期')
    
    查询 = 画材包分发记录.query
    
    if 开始日期:
        查询 = 查询.filter(画材包分发记录.分发时间 >= datetime.strptime(开始日期, '%Y-%m-%d'))
    if 结束日期:
        查询 = 查询.filter(画材包分发记录.分发时间 <= datetime.strptime(结束日期 + ' 23:59:59', '%Y-%m-%d %H:%M:%S'))
    
    记录列表 = 查询.order_by(画材包分发记录.分发时间.desc()).all()
    
    导出数据 = []
    for 记录 in 记录列表:
        导出数据.append({
            '分发记录编号': 记录.分发记录编号,
            '学号': 记录.学号,
            '学生姓名': 记录.领取学生.姓名,
            '班级编号': 记录.领取学生.班级编号,
            '班级名称': 记录.领取学生.所属班级.班级名称,
            '包类型编号': 记录.包类型编号,
            '包类型名称': 记录.包类型.包类型名称,
            '适用课程': 记录.包类型.适用课程,
            '分发时间': 记录.分发时间.strftime('%Y-%m-%d %H:%M:%S'),
            '分发人': 记录.分发人,
            '领取状态': 记录.领取状态,
            '补领标记': '是' if 记录.补领标记 else '否',
            '原分发记录编号': 记录.原分发记录编号 or '',
            '备注': 记录.备注 or ''
        })
    
    if 格式 == 'table':
        表头 = ['分发记录编号', '学号', '学生姓名', '班级名称', '包类型名称', '分发时间', '领取状态', '补领标记', '备注']
        表格内容 = '| ' + ' | '.join(表头) + ' |\n'
        表格内容 += '| ' + ' | '.join(['---' for _ in 表头]) + ' |\n'
        for 行 in 导出数据:
            表格行 = [str(行[列]) for 列 in 表头]
            表格内容 += '| ' + ' | '.join(表格行) + ' |\n'
        return 表格内容, 200, {'Content-Type': 'text/markdown; charset=utf-8'}
    
    return jsonify({
        '导出时间': datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
        '记录总数': len(导出数据),
        '分发记录清单': 导出数据
    }), 200


@app.route('/api/import', methods=['POST'])
def 导入分发记录():
    if '文件' not in request.files:
        return jsonify({
            '错误码': 'FILE_MISSING',
            '错误信息': '未找到上传的文件',
            '建议操作': '请选择要导入的文件后重试'
        }), 400
    
    文件 = request.files['文件']
    if 文件.filename == '':
        return jsonify({
            '错误码': 'EMPTY_FILENAME',
            '错误信息': '文件名为空',
            '建议操作': '请选择有效的文件后重试'
        }), 400
    
    try:
        内容 = 文件.read().decode('utf-8')
        导入数据 = json.loads(内容)
    except Exception as e:
        return jsonify({
            '错误码': 'FILE_PARSE_ERROR',
            '错误信息': '文件解析失败，请确保是有效的JSON格式',
            '错误详情': str(e),
            '建议操作': '请检查文件格式是否正确'
        }), 400
    
    成功记录 = []
    失败记录 = []
    
    for 序号, 行数据 in enumerate(导入数据, 1):
        try:
            必填字段 = ['学号', '包类型编号']
            缺失字段 = [字段 for 字段 in 必填字段 if 字段 not in 行数据 or not 行数据[字段]]
            if 缺失字段:
                失败记录.append({
                    '行号': 序号,
                    '错误码': 'MISSING_REQUIRED_FIELDS',
                    '错误信息': f'缺少必填字段: {", ".join(缺失字段)}',
                    '行数据': 行数据
                })
                continue
            
            学号 = 行数据['学号']
            包类型编号 = 行数据['包类型编号']
            
            学生信息 = 学生.query.get(学号)
            if not 学生信息:
                失败记录.append({
                    '行号': 序号,
                    '错误码': 'STUDENT_NOT_FOUND',
                    '错误信息': f'未找到学号为 {学号} 的学生',
                    '行数据': 行数据
                })
                continue
            
            包类型信息 = 画材包类型.query.get(包类型编号)
            if not 包类型信息:
                失败记录.append({
                    '行号': 序号,
                    '错误码': 'PACKAGE_NOT_FOUND',
                    '错误信息': f'未找到编号为 {包类型编号} 的画材包类型',
                    '行数据': 行数据
                })
                continue
            
            库存信息 = 画材库存.query.filter_by(包类型编号=包类型编号).first()
            if not 库存信息 or 库存信息.当前库存量 <= 0:
                失败记录.append({
                    '行号': 序号,
                    '错误码': 'INVENTORY_SHORTAGE',
                    '错误信息': f'画材包 {包类型信息.包类型名称} 库存不足',
                    '行数据': 行数据
                })
                continue
            
            已有记录 = 画材包分发记录.query.filter_by(
                学号=学号,
                包类型编号=包类型编号,
                领取状态='已领取'
            ).first()
            
            if 已有记录:
                异常编号 = 记录异常(
                    异常类型='导入重复分发冲突',
                    异常描述=f'导入时发现学生 {学生信息.姓名} 已领取过 {包类型信息.包类型名称}',
                    涉及学号=学号,
                    涉及分发记录编号=已有记录.分发记录编号,
                    涉及包类型编号=包类型编号
                )
                失败记录.append({
                    '行号': 序号,
                    '错误码': 'DUPLICATE_RECORD',
                    '错误信息': '该学生已领取过此画材包，禁止静默覆盖',
                    '异常编号': 异常编号,
                    '已有分发记录编号': 已有记录.分发记录编号,
                    '行数据': 行数据
                })
                continue
            
            分发记录编号 = 生成分发记录编号()
            库存信息.当前库存量 -= 1
            
            新记录 = 画材包分发记录(
                分发记录编号=分发记录编号,
                学号=学号,
                包类型编号=包类型编号,
                分发人=行数据.get('分发人', '批量导入'),
                领取状态='已领取',
                领取确认时间=datetime.now(),
                补领标记=行数据.get('补领标记', False),
                备注=行数据.get('备注')
            )
            db.session.add(新记录)
            
            成功记录.append({
                '行号': 序号,
                '分发记录编号': 分发记录编号,
                '学号': 学号,
                '学生姓名': 学生信息.姓名,
                '包类型名称': 包类型信息.包类型名称
            })
            
        except Exception as e:
            失败记录.append({
                '行号': 序号,
                '错误码': 'ROW_PROCESS_ERROR',
                '错误信息': f'处理该行时发生错误: {str(e)}',
                '行数据': 行数据
            })
    
    db.session.commit()
    
    return jsonify({
        '状态': '完成',
        '导入统计': {
            '总行数': len(导入数据),
            '成功行数': len(成功记录),
            '失败行数': len(失败记录)
        },
        '成功记录明细': 成功记录,
        '失败记录明细': 失败记录
    }), 200


