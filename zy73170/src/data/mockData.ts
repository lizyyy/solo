const makeDraft = (
  sampleId: string,
  lines: Array<{ n: number; text: string; w?: string; color?: string }>,
) =>
  lines.map((l) => ({
    id: `${sampleId}-d${l.n}`,
    sampleId,
    lineNumber: l.n,
    content: l.text,
    isWithdrawn: !!l.w,
    withdrawnAt: l.w,
    clueColor: l.color,
  }));

const makeSteps = (
  sampleId: string,
  steps: Array<{ n: number; desc: string; val: string; clue: string; ref: string; color?: string }>,
) =>
  steps.map((s) => ({
    id: `${sampleId}-s${s.n}`,
    sampleId,
    stepNumber: s.n,
    description: s.desc,
    value: s.val,
    sourceClue: s.clue,
    sourceRef: s.ref,
    clueColor: s.color,
  }));

