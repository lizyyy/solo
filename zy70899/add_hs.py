with open('services.py', 'a') as f:
    f.write('\n')
    f.write('class HandoverService:\n')
    f.write('    @staticmethod\n')
    f.write('    def create_handover(db, handover_data):\n')
    f.write('        task_id = generate_task_id()\n')
    f.write('        raw_data = json.dumps(handover_data.model_dump(), ensure_ascii=False, default=json_serializer)\n')
    f.write('        db_handover = TellerBoxHandover(\n')
    f.write('            task_id=task_id,\n')
    f.write('            branch_id=handover_data.branch_id,\n')
    f.write('            branch_name=handover_data.branch_name,\n')
    f.write('            handover_date=handover_data.handover_date,\n')
    f.write('            handover_type=handover_data.handover_type,\n')
    f.write('            box_no=handover_data.box_no,\n')
    f.write('            box_amount=handover_data.box_amount,\n')
    f.write('            error_no=handover_data.error_no,\n')
    f.write('            handler1_id=handover_data.handler1_id,\n')
    f.write('            handler1_name=handover_data.handler1_name,\n')
    f.write('            handler2_id=handover_data.handler2_id,\n')
    f.write('            handler2_name=handover_data.handler2_name,\n')
    f.write('            is_cross_day=handover_data.is_cross_day,\n')
    f.write('            previous_unclosed_reason=handover_data.previous_unclosed_reason,\n')
    f.write('            raw_data=raw_data,\n')
    f.write('            raw_data_position=handover_data.raw_data_position,\n')
    f.write('            created_by=handover_data.created_by,\n')
    f.write('            status=TaskStatus.PROCESSING\n')
    f.write('        )\n')
    f.write('        db.add(db_handover)\n')
    f.write('        db.commit()\n')
    f.write('        db.refresh(db_handover)\n')
    f.write('        result = DataClassifier.classify(db_handover, db)\n')
    f.write('        db_handover.category = result.category\n')
    f.write('        db_handover.category_reason = result.category_reason\n')
    f.write('        db_handover.subsequent_action = result.subsequent_action\n')
    f.write('        db_handover.error_details = result.error_details\n')
    f.write('        if result.category == DataCategory.BLOCKED:\n')
    f.write('            db_handover.status = TaskStatus.FAILED\n')
    f.write('        elif result.category == DataCategory.PENDING_SUPPLEMENT:\n')
    f.write('            db_handover.status = TaskStatus.MANUAL_CONFIRM\n')
    f.write('        db.commit()\n')
    f.write('        db.refresh(db_handover)\n')
    f.write('        return db_handover\n')
    f.write('\n')
    f.write('    @staticmethod\n')
    f.write('    def get_handover_by_task_id(db, task_id):\n')
    f.write('        return db.query(TellerBoxHandover).filter(TellerBoxHandover.task_id == task_id).first()\n')
    f.write('\n')
    f.write('    @staticmethod\n')
    f.write('    def list_handovers(db, skip=0, limit=100, status=None, category=None):\n')
    f.write('        query = db.query(TellerBoxHandover)\n')
    f.write('        if status:\n')
    f.write('            query = query.filter(TellerBoxHandover.status == status)\n')
    f.write('        if category:\n')
    f.write('            query = query.filter(TellerBoxHandover.category == category)\n')
    f.write('        total = query.count()\n')
    f.write('        items = query.order_by(TellerBoxHandover.created_at.desc()).offset(skip).limit(limit).all()\n')
    f.write('        return total, items\n')
    f.write('\n')
    f.write('    @staticmethod\n')
    f.write('    def update_conclusion(db, task_id, update_data):\n')
    f.write('        handover = HandoverService.get_handover_by_task_id(db, task_id)\n')
    f.write('        if not handover:\n')
    f.write('            return None\n')
    f.write('        audit_log = AuditLog(\n')
    f.write('            handover_id=handover.id,\n')
    f.write('            task_id=task_id,\n')
    f.write('            field_changed=update_data.field_changed,\n')
    f.write('            old_value=update_data.old_value,\n')
    f.write('            new_value=update_data.new_value,\n')
    f.write('            change_reason=update_data.change_reason,\n')
    f.write('            changed_by_id=update_data.changed_by_id,\n')
    f.write('            changed_by_name=update_data.changed_by_name,\n')
    f.write('        )\n')
    f.write('        db.add(audit_log)\n')
    f.write('        if update_data.field_changed == "category":\n')
    f.write('            handover.category = update_data.new_value\n')
    f.write('        elif update_data.field_changed == "status":\n')
    f.write('            handover.status = update_data.new_value\n')
    f.write('        elif update_data.field_changed == "category_reason":\n')
    f.write('            handover.category_reason = update_data.new_value\n')
    f.write('        elif update_data.field_changed == "subsequent_action":\n')
    f.write('            handover.subsequent_action = update_data.new_value\n')
    f.write('        db.commit()\n')
    f.write('        db.refresh(audit_log)\n')
    f.write('        return audit_log\n')
    f.write('\n')
    f.write('    @staticmethod\n')
    f.write('    def get_audit_logs(db, task_id):\n')
    f.write('        return db.query(AuditLog).filter(AuditLog.task_id == task_id).order_by(AuditLog.changed_at.desc()).all()\n')
    f.write('\n')
    f.write('    @staticmethod\n')
    f.write('    def get_field_traces(db, task_id):\n')
    f.write('        return db.query(FieldTrace).filter(FieldTrace.task_id == task_id).all()\n')
    f.write('\n')
    f.write('    @staticmethod\n')
    f.write('    def update_status(db, task_id, new_status):\n')
    f.write('        handover = HandoverService.get_handover_by_task_id(db, task_id)\n')
    f.write('        if not handover:\n')
    f.write('            return None\n')
    f.write('        handover.status = new_status\n')
    f.write('        db.commit()\n')
    f.write('        db.refresh(handover)\n')
    f.write('        return handover\n')
    f.write('\n')
    f.write('    @staticmethod\n')
    f.write('    def get_raw_data(db, task_id):\n')
    f.write('        handover = HandoverService.get_handover_by_task_id(db, task_id)\n')
    f.write('        if not handover:\n')
    f.write('            return None\n')
    f.write('        return json.loads(handover.raw_data)\n')

print('Done')
