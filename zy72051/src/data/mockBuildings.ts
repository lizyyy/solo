export const getBuildingById = (id: string): Building | undefined => {
  return mockBuildings.find(b => b.id === id);
};

export const detectDuplicates = (buildings: Building[]): Map<string, Building[]> => {
  const nameMap = new Map<string, Building[]>();
  buildings.forEach(b => {
    b.deviceNames.forEach(name => {
      const normalized = name.toLowerCase().replace(/[^a-z0-9\u4e00-\u9fa5]/g, '');
      if (!nameMap.has(normalized)) nameMap.set(normalized, []);
      nameMap.get(normalized)!.push(b);
    });
  });
  for (const [key, list] of nameMap) {
    if (list.length <= 1) nameMap.delete(key);
  }
  return nameMap;
};
