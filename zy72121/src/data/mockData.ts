export const parseRawData = (text: string): Partial<InspectionRecord>[] => {
  const lines = text.trim().split('\n');
  const headers = lines[0].split(/[\t,]/).map(h => h.trim());
  
  return lines.slice(1).map((line, idx) => {
    const values = line.split(/[\t,]/).map(v => v.trim());
    const record: Record<string, string> = {};
    headers.forEach((h, i) => {
      record[h] = values[i] || '';
    });

    return {
      id: `rec_import_${idx}_${Date.now()}`,
      location: record['位置'] || record['location'] || '',
      curtainType: record['门帘类型'] || record['curtainType'] || '',
      temperatureInside: parseFloat(record['库内温度'] || record['temperatureInside'] || '') || null,
      tempInsideUnit: record['库内温度单位'] || record['tempInsideUnit'] || '°C',
      temperatureOutside: parseFloat(record['库外温度'] || record['temperatureOutside'] || '') || null,
      tempOutsideUnit: record['库外温度单位'] || record['tempOutsideUnit'] || '°C',
      curtainArea: parseFloat(record['门帘面积'] || record['curtainArea'] || '') || null,
      areaUnit: record['面积单位'] || record['areaUnit'] || 'm²',
      airChangeRate: parseFloat(record['换气次数'] || record['airChangeRate'] || '') || null,
      samplingTime: record['采样时间'] || record['samplingTime'] || new Date().toISOString(),
      source: '手动导入',
    };
  });
};
