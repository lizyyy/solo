export function createSampleCSVContent(): string {
  const headers = ['orderNo', 'elderId', 'elderName', 'nurseId', 'nurseName', 'serviceDate', 'serviceTime', 'serviceItems', 'actualDuration', 'status', 'cancelReason', 'signedBy'];
  const rows = sampleServiceOrders.map(o => [
    o.orderNo,
    o.elderId,
    o.elderName,
    o.nurseId,
    o.nurseName,
    o.serviceDate,
    o.serviceTime,
    o.serviceItems.join(','),
    o.actualDuration.toString(),
    o.status === 'completed' ? '已完成' : o.status === 'cancelled' ? '已取消' : '待处理',
    o.cancelReason || '',
    o.signedBy || '',
  ]);
  return [headers.join(','), ...rows.map(r => r.join(','))].join('\n');
}
